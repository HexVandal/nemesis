"""Markdown report writer - the format most people actually read."""

from __future__ import annotations

from pathlib import Path

from ..models import Finding, ScanResult, Severity

_SEVERITY_ORDER = [
    Severity.CRITICAL,
    Severity.HIGH,
    Severity.MEDIUM,
    Severity.LOW,
    Severity.INFO,
]


def _escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _finding_block(finding: Finding, index: int) -> str:
    lines: list[str] = []
    lines.append(f"### {index}. {finding.title}")
    lines.append("")
    lines.append(
        f"| | |\n|---|---|\n"
        f"| **Severity** | {finding.severity.name} |\n"
        f"| **Confidence** | {finding.confidence.value} |\n"
        f"| **Target** | `{_escape(finding.target)}` |\n"
        f"| **Module** | `{finding.module}` |"
    )
    if finding.cwe:
        lines.append(f"| **CWE** | [{finding.cwe}](https://cwe.mitre.org/data/definitions/{finding.cwe.split('-')[-1]}.html) |")
    if finding.owasp:
        lines.append(f"| **OWASP** | {finding.owasp} |")
    lines.append("")
    lines.append(finding.description)
    lines.append("")

    if finding.evidence.response:
        snippet = finding.evidence.response[:1200]
        lines.append("<details><summary>Evidence</summary>")
        lines.append("")
        lines.append("```")
        lines.append(snippet)
        lines.append("```")
        lines.append("")
        lines.append("</details>")
        lines.append("")

    if finding.remediation:
        lines.append(f"**Remediation.** {finding.remediation}")
        lines.append("")

    if finding.references:
        lines.append("**References**")
        lines.append("")
        for reference in finding.references:
            lines.append(f"- {reference}")
        lines.append("")

    return "\n".join(lines)


def write_markdown(result: ScanResult, path: str | Path) -> Path:
    """Write a human-readable Markdown report."""
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)

    counts = result.counts()
    lines: list[str] = []
    lines.append(f"# nemesis report - {result.target.base_url}")
    lines.append("")
    lines.append(f"- **Scanned**: {result.started_at} -> {result.finished_at}")
    lines.append(f"- **Duration**: {result.duration_seconds}s")
    lines.append(f"- **Risk score**: {result.risk_score()}/100")
    lines.append(f"- **Endpoints crawled**: {len(result.endpoints)}")
    lines.append(f"- **Forms discovered**: {len(result.forms)}")
    lines.append(f"- **Requests sent**: {result.stats.get('requests_sent', 0)}")
    lines.append("")

    lines.append("## Summary")
    lines.append("")
    lines.append("| Severity | Count |")
    lines.append("|---|---|")
    for severity in _SEVERITY_ORDER:
        lines.append(f"| {severity.name} | {counts[severity.name]} |")
    lines.append(f"| **Total** | **{len(result.findings)}** |")
    lines.append("")

    confirmed = result.confirmed()
    lines.append(
        f"**{len(confirmed)}** of {len(result.findings)} findings are confirmed or "
        "high confidence; the rest need a human to interpret."
    )
    lines.append("")

    if result.technologies:
        lines.append("## Fingerprint")
        lines.append("")
        lines.append("| Technology | Version | Category |")
        lines.append("|---|---|---|")
        for tech in result.technologies:
            lines.append(
                f"| {tech.name} | {tech.version or '-'} | {tech.category} |"
            )
        lines.append("")

    lines.append("## Findings")
    lines.append("")

    index = 0
    for severity in _SEVERITY_ORDER:
        group = [f for f in result.findings if f.severity == severity]
        if not group:
            continue
        lines.append(f"### {severity.name} ({len(group)})")
        lines.append("")
        for finding in group:
            index += 1
            lines.append(_finding_block(finding, index))

    if not result.findings:
        lines.append("_No findings._")
        lines.append("")

    lines.append("---")
    lines.append("")
    lines.append(
        "Generated by [nemesis](https://github.com/HexVandal/nemesis) - the "
        "offensive-security scanner that thinks like a red team."
    )
    lines.append("")

    target.write_text("\n".join(lines), encoding="utf-8")
    return target
